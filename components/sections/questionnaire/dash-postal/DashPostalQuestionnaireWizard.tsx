"use client";

/**
 * Dash Postal and Tax Services' dedicated Project Discovery questionnaire.
 *
 * Same wizard mechanics and shell as components/sections/questionnaire/
 * QuestionnaireWizard.tsx and its Xmine Consult counterpart (progress
 * indicator, inline Back/Next, honeypot, scroll-into-view on step change),
 * but driven by Dash Postal's own draft type, validator, and submit
 * function (lib/questionnaire-dash-postal*.ts) and its own five-section
 * step set, since the question content doesn't fit the generic
 * questionnaire's data shape. Posts to
 * /api/project-questionnaire/dash-postal. The generic questionnaire and
 * Xmine Consult's wizard are both untouched by this file.
 */

import { useEffect, useRef, useState, type ComponentType } from "react";
import Container from "@/components/ui/Container";
import { getButtonClassName } from "@/components/ui/Button";
import {
  createEmptyDashPostalDraft,
  submitDashPostalQuestionnaire,
  type DashPostalQuestionnaireDraft,
  type DashPostalFieldErrors,
} from "@/lib/questionnaire-dash-postal";
import { validateDashPostalQuestionnaire } from "@/lib/questionnaire-dash-postal-validation";
import type { StepId, StepProps } from "./steps/types";
import StepBusinessOverview from "./steps/StepBusinessOverview";
import StepWebsiteGoals from "./steps/StepWebsiteGoals";
import StepBranding from "./steps/StepBranding";
import StepAutomation from "./steps/StepAutomation";
import StepPriorities from "./steps/StepPriorities";
import StepContactReview from "./steps/StepContactReview";

type StepConfig = { id: StepId; title: string };

const STEPS: StepConfig[] = [
  { id: "business", title: "Business Overview" },
  { id: "website", title: "Website Goals" },
  { id: "branding", title: "Branding and Content" },
  { id: "automation", title: "CRM and Business Automation" },
  { id: "priorities", title: "Project Priorities" },
  { id: "contact", title: "Contact & Review" },
];

/** Every step except "contact" (rendered separately below -- it needs the
 * extra onEditStep prop the others don't have). */
const STEP_COMPONENTS: Record<Exclude<StepId, "contact">, ComponentType<StepProps>> = {
  business: StepBusinessOverview,
  website: StepWebsiteGoals,
  branding: StepBranding,
  automation: StepAutomation,
  priorities: StepPriorities,
};

const STEP_REQUIRED_KEYS: Partial<Record<StepId, (keyof DashPostalFieldErrors)[]>> = {
  contact: ["contactName", "contactEmail"],
};

/** `"email_only"` is the honest partial-success state: the notification
 * email reached the team, but Supabase persistence failed. Distinct from
 * `"delivered"` (fully saved) so the copy never implies the data is safe
 * in the CRM when it isn't -- see lib/questionnaire-dash-postal-outcome.ts. */
type Status = "idle" | "submitting" | "delivered" | "email_only" | "error";

/** crypto.randomUUID() isn't available on every browser (e.g. Safari
 * <15.4) -- this is only ever used as an idempotency key, not for anything
 * security-sensitive, so a non-cryptographic fallback is fine. */
function createSubmissionId(): string {
  if (typeof crypto !== "undefined" && typeof crypto.randomUUID === "function") {
    return crypto.randomUUID();
  }
  return `${Date.now()}-${Math.random().toString(36).slice(2)}`;
}

export default function DashPostalQuestionnaireWizard() {
  const [draft, setDraft] = useState<DashPostalQuestionnaireDraft>(() =>
    createEmptyDashPostalDraft()
  );
  const [currentStepId, setCurrentStepId] = useState<StepId>("business");
  const [errors, setErrors] = useState<DashPostalFieldErrors>({});
  const [status, setStatus] = useState<Status>("idle");
  const [statusMessage, setStatusMessage] = useState<string | null>(null);

  // Spam-prevention fields -- same contract as the contact form and the
  // generic questionnaire.
  const [honeypot, setHoneypot] = useState("");
  const [startedAt] = useState(() => Date.now());

  // One id per wizard session, sent with every submit attempt (including
  // retries after a failure) so the server can recognize a double-click or
  // network retry of the *same* submission and never save/notify twice.
  // Only regenerated by resetAll(), when a genuinely new questionnaire
  // starts. See app/api/project-questionnaire/dash-postal/route.ts.
  const [submissionId, setSubmissionId] = useState(() => createSubmissionId());

  const cardRef = useRef<HTMLDivElement>(null);
  const isFirstRender = useRef(true);

  const currentIndex = Math.max(0, STEPS.findIndex((s) => s.id === currentStepId));
  const currentStep = STEPS[currentIndex];
  const isLastStep = currentIndex === STEPS.length - 1;
  const progressPercent = Math.round(((currentIndex + 1) / STEPS.length) * 100);

  useEffect(() => {
    if (isFirstRender.current) {
      isFirstRender.current = false;
      return;
    }
    const prefersReducedMotion = window.matchMedia("(prefers-reduced-motion: reduce)").matches;
    cardRef.current?.scrollIntoView({
      behavior: prefersReducedMotion ? "auto" : "smooth",
      block: "start",
    });
  }, [currentStepId]);

  function update<K extends keyof DashPostalQuestionnaireDraft>(
    key: K,
    value: DashPostalQuestionnaireDraft[K]
  ) {
    setDraft((prev) => ({ ...prev, [key]: value }));
  }

  function stepErrors(stepId: StepId, allErrors: DashPostalFieldErrors): DashPostalFieldErrors {
    const keys = STEP_REQUIRED_KEYS[stepId];
    if (!keys) return {};
    const result: DashPostalFieldErrors = {};
    for (const key of keys) {
      if (allErrors[key]) result[key] = allErrors[key];
    }
    return result;
  }

  function handleBack() {
    if (currentIndex === 0) return;
    setErrors({});
    setCurrentStepId(STEPS[currentIndex - 1].id);
  }

  function handleNext() {
    const validation = validateDashPostalQuestionnaire(draft as unknown as Record<string, unknown>);
    const allErrors = validation.valid ? {} : validation.errors;
    const blocking = stepErrors(currentStep.id, allErrors);

    if (Object.keys(blocking).length > 0) {
      setErrors(blocking);
      return;
    }

    setErrors({});
    if (!isLastStep) {
      setCurrentStepId(STEPS[currentIndex + 1].id);
    }
  }

  function handleEditStep(stepId: StepId) {
    setErrors({});
    setCurrentStepId(stepId);
  }

  async function handleSubmit() {
    if (status === "submitting") return;

    const validation = validateDashPostalQuestionnaire(draft as unknown as Record<string, unknown>);
    if (!validation.valid) {
      setErrors(validation.errors);
      setCurrentStepId("contact");
      return;
    }

    setErrors({});
    setStatus("submitting");
    setStatusMessage(null);

    const result = await submitDashPostalQuestionnaire({
      ...validation.data,
      honeypot,
      startedAt,
      submissionId,
    });

    if (result.ok) {
      setStatus(result.crmSaved ? "delivered" : "email_only");
      return;
    }

    switch (result.error) {
      case "validation_failed":
        setErrors(result.fieldErrors ?? {});
        setCurrentStepId("contact");
        setStatus("idle");
        return;
      case "rate_limited":
        setStatus("error");
        setStatusMessage(
          "You’ve submitted a few of these recently — please wait a few minutes and try again."
        );
        return;
      default:
        // Covers "submission_failed" (neither the CRM save nor the email
        // went through) as well as a genuine network error -- in both
        // cases nothing happened, the draft above is untouched, and
        // clicking "Submit Questionnaire" again safely retries: the same
        // submissionId means a duplicate send can never happen, and a
        // real failure is never cached server-side, so this genuinely
        // re-attempts rather than replaying a stale result.
        setStatus("error");
        setStatusMessage(
          "We couldn’t save or send this just now. Your answers are still here — please try again in a moment."
        );
    }
  }

  function resetAll() {
    setDraft(createEmptyDashPostalDraft());
    setCurrentStepId("business");
    setErrors({});
    setStatus("idle");
    setStatusMessage(null);
    setSubmissionId(createSubmissionId());
  }

  if (status === "delivered" || status === "email_only") {
    return (
      <section className="bg-paper-dim py-20 sm:py-28">
        <Container>
          <div
            role="status"
            className="mx-auto flex max-w-xl flex-col items-center gap-4 rounded-3xl border border-line bg-paper p-10 text-center sm:p-14"
          >
            <span
              aria-hidden="true"
              className="inline-flex h-12 w-12 items-center justify-center rounded-full bg-ink text-gold-bright"
            >
              ✓
            </span>
            <h2 className="text-2xl font-semibold text-ink">
              {status === "delivered" ? "Thank You" : "Received"}
            </h2>
            <p className="text-base leading-relaxed text-slate">
              {status === "delivered" ? (
                <>
                  Thank you for telling us about Dash Postal and Tax Services. We&rsquo;ve
                  received your information and will review it ahead of our consultation.
                  Someone from Ananse Automation will follow up with you.
                </>
              ) : (
                <>
                  We&rsquo;ve received your information by email, but weren&rsquo;t able to save
                  it to our system just now. Your answers aren&rsquo;t lost — our team has still
                  been notified and will follow up with you, and will add this manually.
                </>
              )}
            </p>
            <button
              type="button"
              onClick={resetAll}
              className="mt-2 text-sm font-medium text-gold hover:text-gold-bright"
            >
              Start another questionnaire
            </button>
          </div>
        </Container>
      </section>
    );
  }

  const StepComponent =
    currentStep.id === "contact" ? null : STEP_COMPONENTS[currentStep.id as Exclude<StepId, "contact">];

  return (
    <section className="bg-paper-dim py-16 sm:py-24">
      <Container>
        <div
          ref={cardRef}
          className="mx-auto flex w-full max-w-3xl scroll-mt-24 flex-col gap-8 rounded-3xl border border-line bg-paper p-6 sm:p-10"
        >
          {/* Honeypot: invisible and unreachable for real visitors -- see
              components/sections/contact/ContactForm.tsx for the identical
              pattern. */}
          <div className="absolute -left-[9999px]" aria-hidden="true">
            <label htmlFor="dash-postal-questionnaire-company-website">
              Leave this field blank
            </label>
            <input
              id="dash-postal-questionnaire-company-website"
              type="text"
              name="company_website"
              tabIndex={-1}
              autoComplete="off"
              value={honeypot}
              onChange={(e) => setHoneypot(e.target.value)}
            />
          </div>

          <ProgressIndicator
            stepNumber={currentIndex + 1}
            totalSteps={STEPS.length}
            title={currentStep.title}
            percent={progressPercent}
          />

          {currentStep.id === "contact" || !StepComponent ? (
            <StepContactReview draft={draft} update={update} errors={errors} onEditStep={handleEditStep} />
          ) : (
            <StepComponent draft={draft} update={update} errors={errors} />
          )}

          {status === "error" && statusMessage ? (
            <p role="alert" className="text-sm text-terracotta">
              {statusMessage}
            </p>
          ) : null}

          <div className="flex items-center justify-between gap-3 border-t border-line pt-6">
            <button
              type="button"
              onClick={handleBack}
              disabled={currentIndex === 0}
              className={getButtonClassName({
                variant: "secondary",
                className: "disabled:pointer-events-none disabled:opacity-40",
              })}
            >
              Back
            </button>

            {isLastStep ? (
              <button
                type="button"
                onClick={handleSubmit}
                disabled={status === "submitting"}
                className={getButtonClassName({
                  className: "disabled:pointer-events-none disabled:opacity-60",
                })}
              >
                {status === "submitting" ? "Sending…" : "Submit Questionnaire"}
              </button>
            ) : (
              <button type="button" onClick={handleNext} className={getButtonClassName()}>
                Next
              </button>
            )}
          </div>
        </div>
      </Container>
    </section>
  );
}

function ProgressIndicator({
  stepNumber,
  totalSteps,
  title,
  percent,
}: {
  stepNumber: number;
  totalSteps: number;
  title: string;
  percent: number;
}) {
  return (
    <div className="flex flex-col gap-2.5">
      <div className="flex items-center justify-between gap-3">
        <span className="font-mono text-xs font-medium tracking-[0.15em] text-gold uppercase">
          Step {stepNumber} of {totalSteps}
        </span>
        <span className="text-sm font-medium text-ink">{title}</span>
      </div>
      <div
        role="progressbar"
        aria-valuenow={percent}
        aria-valuemin={0}
        aria-valuemax={100}
        aria-label={`Questionnaire progress: step ${stepNumber} of ${totalSteps}`}
        className="h-1.5 w-full overflow-hidden rounded-full bg-line"
      >
        <div
          className="h-full rounded-full bg-gold transition-[width] duration-300 ease-out"
          style={{ width: `${percent}%` }}
        />
      </div>
    </div>
  );
}
